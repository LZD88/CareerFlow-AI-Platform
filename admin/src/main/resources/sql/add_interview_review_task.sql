-- 面试复盘任务表

CREATE TABLE IF NOT EXISTS interview_review_task (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
    title VARCHAR(255) NOT NULL COMMENT '任务标题',
    candidate_name VARCHAR(100) DEFAULT NULL COMMENT '候选人姓名',
    interview_role VARCHAR(100) DEFAULT NULL COMMENT '面试岗位',
    original_filename VARCHAR(255) NOT NULL COMMENT '原始音频文件名',
    audio_object_key VARCHAR(500) NOT NULL COMMENT 'TOS 对象 Key',
    audio_url VARCHAR(1000) NOT NULL COMMENT 'TOS 文件访问地址',
    audio_content_type VARCHAR(100) DEFAULT NULL COMMENT '音频 Content-Type',
    audio_size BIGINT NOT NULL COMMENT '音频文件大小，单位字节',
    resume_filename VARCHAR(255) DEFAULT NULL COMMENT '简历原始文件名',
    resume_object_key VARCHAR(500) DEFAULT NULL COMMENT '简历 TOS 对象 Key',
    resume_url VARCHAR(1000) DEFAULT NULL COMMENT '简历文件访问地址',
    resume_content_type VARCHAR(100) DEFAULT NULL COMMENT '简历 Content-Type',
    resume_size BIGINT DEFAULT NULL COMMENT '简历文件大小，单位字节',
    status VARCHAR(32) NOT NULL DEFAULT 'UPLOADED' COMMENT '状态：UPLOADED 已上传 / TRANSCRIBING 转写中 / TRANSCRIBED 已转写 / REVIEWING 复盘中 / DONE 已完成 / FAILED 失败',
    transcript_text MEDIUMTEXT DEFAULT NULL COMMENT 'ASR 转写文本',
    review_report MEDIUMTEXT DEFAULT NULL COMMENT '复盘报告',
    fail_reason TEXT DEFAULT NULL COMMENT '失败原因',
    question_status VARCHAR(32) NOT NULL DEFAULT 'NONE' COMMENT '题库生成状态：NONE 未生成 / PROCESSING 生成中 / DONE 已生成 / FAILED 失败',
    question_extracted_count INT NOT NULL DEFAULT 0 COMMENT '题库抽取问题数',
    question_created_count INT NOT NULL DEFAULT 0 COMMENT '题库新增问题数',
    question_merged_count INT NOT NULL DEFAULT 0 COMMENT '题库合并问题数',
    question_fail_reason TEXT DEFAULT NULL COMMENT '题库生成失败原因',
    created_by BIGINT DEFAULT NULL COMMENT '创建人',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    KEY idx_status (status),
    KEY idx_question_status (question_status),
    KEY idx_created_at (created_at),
    KEY idx_created_by (created_by),
    KEY idx_title (title(191)),
    KEY idx_candidate_name (candidate_name)
) COMMENT='面试复盘任务';
